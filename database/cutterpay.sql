-- 1. Usuarios: datos personales, rol y estado de la cuenta
CREATE TABLE usuarios (
  id                SERIAL PRIMARY KEY,
  nombre            VARCHAR(80)  NOT NULL,
  correo            VARCHAR(120) NOT NULL UNIQUE,
  password_hash     VARCHAR(100) NOT NULL,
  dpi               VARCHAR(13),
